"""Draw the application icon and write every file that consumes it.

The design lives in ``proxy/assets/icon.svg``.  Pillow cannot rasterise SVG, so
this script repeats the same geometry with drawing primitives (4x supersampling,
then a LANCZOS downscale) and produces:

    proxy/assets/icon.png    256x256, for the site and for reference
    proxy/assets/icon.ico    16..256, handed to PyInstaller as --icon
    proxy/icon.py            the mark embedded as base64 for tkinter

Run it after editing the SVG:  python tools/make_icon.py
"""

from __future__ import annotations

import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'proxy' / 'assets'
ICON_MODULE = ROOT / 'proxy' / 'icon.py'

SIZE = 256
SCALE = 4
CANVAS = SIZE * SCALE

TOP = (0x4A, 0xA8, 0xFF)
BOTTOM = (0x0A, 0x5C, 0xC4)
WHITE = (255, 255, 255, 255)

ICO_SIZES = [(16, 16), (24, 24), (32, 32), (48, 48), (64, 64), (128, 128), (256, 256)]

MODULE_HEADER = '''"""Window icon for the program (generated by tools/make_icon.py).

The PNG travels inside this module: a PyInstaller onefile build carries no data
files next to the EXE, and tkinter still needs image bytes to show an icon.
"""

from __future__ import annotations

import tkinter as tk

# 64x64 PNG, base64 encoded.  Regenerate with: python tools/make_icon.py
ICON_PNG_64 = (
%s
)

_KEEP = []


def apply(window) -> None:
    """Set *window*'s icon; a Tk without PNG support simply stays iconless."""
    try:
        image = tk.PhotoImage(data=ICON_PNG_64)
    except Exception:
        return
    try:
        window.iconphoto(True, image)
    except Exception:
        return
    _KEEP.append(image)                      # tkinter keeps no reference itself
'''


def gradient(size: int) -> Image.Image:
    """Diagonal gradient, drawn small and scaled up: smooth and quick."""
    small = Image.new('RGB', (64, 64))
    pixels = small.load()
    for y in range(64):
        for x in range(64):
            ratio = (x + y) / 126.0
            pixels[x, y] = tuple(round(start + (end - start) * ratio)
                                 for start, end in zip(TOP, BOTTOM))
    return small.resize((size, size), Image.LANCZOS)


def draw_icon(size: int = CANVAS) -> Image.Image:
    factor = size / SIZE
    image = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        [0, 0, size - 1, size - 1], radius=int(56 * factor), fill=255)
    image.paste(gradient(size), (0, 0), mask)

    pen = ImageDraw.Draw(image)
    width = max(1, int(18 * factor))
    half = width // 2

    def bar(x1: float, y1: float, x2: float, y2: float, colour) -> None:
        points = [(x1 * factor, y1 * factor), (x2 * factor, y2 * factor)]
        pen.line(points, fill=colour, width=width)
        for x, y in points:                  # round caps, like stroke-linecap
            pen.ellipse([x - half, y - half, x + half, y + half], fill=colour)

    def head(points, colour) -> None:
        pen.polygon([(x * factor, y * factor) for x, y in points], fill=colour)

    bar(54, 86, 164, 86, WHITE)              # request: goes right
    head([(164, 68), (204, 86), (164, 104)], WHITE)
    bar(202, 170, 92, 170, WHITE)            # response: comes back
    head([(92, 152), (52, 170), (92, 188)], WHITE)
    return image


def write_module(master: Image.Image) -> tuple[int, int]:
    buffer = io.BytesIO()
    master.resize((64, 64), Image.LANCZOS).save(buffer, format='PNG', optimize=True)
    payload = base64.b64encode(buffer.getvalue()).decode('ascii')
    lines = '\n'.join("    '%s'" % payload[index:index + 72]
                      for index in range(0, len(payload), 72))
    ICON_MODULE.write_text(MODULE_HEADER % lines, encoding='utf-8')
    return len(payload), len(buffer.getvalue())


def main() -> int:
    ASSETS.mkdir(parents=True, exist_ok=True)
    master = draw_icon().resize((SIZE, SIZE), Image.LANCZOS)
    master.save(ASSETS / 'icon.png')
    master.save(ASSETS / 'icon.ico', sizes=ICO_SIZES)
    encoded, raw = write_module(master)
    print('icon.png  %d bytes' % (ASSETS / 'icon.png').stat().st_size)
    print('icon.ico  %d bytes' % (ASSETS / 'icon.ico').stat().st_size)
    print('icon.py   %d bytes (base64 %d, png %d)' % (ICON_MODULE.stat().st_size, encoded, raw))
    print('ICON_OK')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
