"""Draw the application icon and write every file that consumes it.

The design lives in ``proxy/assets/icon.svg``.  Pillow cannot rasterise SVG, so
this script repeats the same geometry with drawing primitives (4x supersampling,
then a LANCZOS downscale) and produces:

    proxy/assets/icon.png    256x256, for the site and for reference
    proxy/assets/icon.ico    16..256, handed to PyInstaller as --icon
    proxy/icon.py            the mark embedded as base64 for tkinter

Run it after editing the SVG:  python tools/make_icon.py
"""

from __future__ import annotations

import base64
import io
from pathlib import Path

from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / 'proxy' / 'assets'
ICON_MODULE = ROOT / 'proxy' / 'icon.py'

SIZE = 256
SCALE = 4
CANVAS = SIZE * SCALE

TOP = (0x4A, 0xA8, 0xFF)
BOTTOM = (0x0A, 0x5C, 0xC4)
WHITE = (255, 255, 255, 255)

ICO_SIZES = [16, 24, 32, 48, 64, 128, 256]

MODULE_HEADER = '''"""Window icon for the program (generated by tools/make_icon.py).

The PNGs travel inside this module: a PyInstaller onefile build carries no data
files next to the EXE, and tkinter still needs image bytes to show an icon.

Several sizes are embedded rather than one: ``iconphoto`` handed a single 64x64
bitmap makes Windows scale it for the title bar, which looks soft at high DPI
(150 to 200 percent).  Passing every size lets Tk pick the one matching the
screen, so the title bar icon stays crisp at any scaling level.
"""

from __future__ import annotations

import sys
import tkinter as tk

# Base64-encoded PNGs, largest first.  Regenerate with: python tools/make_icon.py
ICON_PNGS = (
%s
)

_KEEP = []


def init_app_id() -> None:
    """Give the process a stable AppUserModelID before any window is shown.

    Without one, Windows groups the app under its host executable (python.exe
    when run from source) and shows that program's icon in the taskbar instead
    of the window icon set by ``apply``.  No-op off Windows; on Windows the
    shell call is made directly and any failure propagates to the caller,
    which is best placed to report it without aborting startup.
    """
    if sys.platform != 'win32':
        return
    import ctypes
    ctypes.windll.shell32.SetCurrentProcessExplicitAppUserModelID(
        'ServerProtocolBridge.1')


def apply(window, report=None) -> None:
    """Set *window*'s icon.

    Every embedded size is handed to iconphoto so Tk selects the one matching
    the screen's DPI; a single image would be scaled by Windows and look soft.

    *report* receives a human-readable line for each size this Tk build cannot
    decode (a Tk without PNG support).  When *report* is None the lines go to
    stderr, so a decoding failure is never silent.  Any other error propagates.
    """
    if report is None:
        def report(message):
            print(message, file=sys.stderr)

    images = []
    for payload in ICON_PNGS:
        try:
            image = tk.PhotoImage(data=payload)
        except tk.TclError as exc:           # a Tk without PNG cannot decode any size
            report('icon: ' + str(exc))
            continue
        images.append(image)
    if not images:
        report('icon: no decodable size; window stays iconless')
        return
    window.iconphoto(True, *images)
    _KEEP.extend(images)                     # tkinter keeps no reference itself
    # CustomTkinter schedules its own title-bar icon 200ms after the window is
    # created and backs off only when iconbitmap() was called.  iconphoto() is
    # invisible to that check, so without this flag the CTk default icon would
    # replace ours a moment later.
    if hasattr(window, '_iconbitmap_method_called'):
        window._iconbitmap_method_called = True
'''


def gradient(size: int) -> Image.Image:
    """Diagonal gradient, drawn small and scaled up: smooth and quick."""
    small = Image.new('RGB', (64, 64))
    pixels = small.load()
    for y in range(64):
        for x in range(64):
            ratio = (x + y) / 126.0
            pixels[x, y] = tuple(round(start + (end - start) * ratio)
                                 for start, end in zip(TOP, BOTTOM))
    return small.resize((size, size), Image.LANCZOS)


SIMPLE_MAX = 40


def draw_icon(size: int = CANVAS, simple: bool = False) -> Image.Image:
    """The mark, drawn natively at *size*.

    ``simple`` swaps the arrowheads for compact ones.  Below about 40px the
    full geometry does not survive a downscale: the two heads smear into short
    lines and the mark reads as "two dashes".  Redrawn natively on fatter
    strokes the same two arrows stay readable at 16px.
    """
    factor = size / SIZE
    image = Image.new('RGBA', (size, size), (0, 0, 0, 0))
    mask = Image.new('L', (size, size), 0)
    ImageDraw.Draw(mask).rounded_rectangle(
        [0, 0, size - 1, size - 1], radius=int(56 * factor), fill=255)
    image.paste(gradient(size), (0, 0), mask)

    pen = ImageDraw.Draw(image)
    half = max(1, int(9 * factor))

    def bar(x1: float, y1: float, x2: float, y2: float, colour=WHITE) -> None:
        points = [(x1 * factor, y1 * factor), (x2 * factor, y2 * factor)]
        pen.line(points, fill=colour, width=half * 2)
        for x, y in points:                  # round caps, like stroke-linecap
            pen.ellipse([x - half, y - half, x + half, y + half], fill=colour)

    def head(points, colour=WHITE) -> None:
        pen.polygon([(x * factor, y * factor) for x, y in points], fill=colour)

    if simple:
        # Bold geometry for the tiny sizes: a head ~a quarter of the canvas and
        # a short shaft.  The full mark's heads smear into stubs below 40px, so
        # the arrows are redrawn much chunkier (centres: 144,88 / 112,168).
        bar(36, 88, 100, 88, WHITE)
        head([(96, 60), (192, 88), (96, 116)], WHITE)
        bar(220, 168, 156, 168, WHITE)
        head([(160, 140), (64, 168), (160, 196)], WHITE)
    else:
        bar(54, 86, 164, 86, WHITE)          # request: goes right
        head([(164, 68), (204, 86), (164, 104)], WHITE)
        bar(202, 170, 92, 170, WHITE)        # response: comes back
        head([(92, 152), (52, 170), (92, 188)], WHITE)
    return image


def render(size: int) -> Image.Image:
    """A crisp ``size`` x ``size`` master: 4x supersampled, then downscaled."""
    master = draw_icon(size * SCALE, simple=size <= SIMPLE_MAX)
    return master.resize((size, size), Image.LANCZOS)


# Tk picks the size matching the screen, so the list runs from the largest size
# the shell ever asks for down to the 16px title bar.  Sizes at or below
# SIMPLE_MAX are redrawn rather than downscaled (see draw_icon).
MODULE_SIZES = [96, 48, 32, 24, 16]


def _encode(size: int) -> str:
    """Base64 PNG of the icon at *size*, wrapped as source lines."""
    buffer = io.BytesIO()
    render(size).save(buffer, format='PNG', optimize=True)
    payload = base64.b64encode(buffer.getvalue()).decode('ascii')
    return '\n'.join("    '%s'" % payload[index:index + 72]
                     for index in range(0, len(payload), 72))


def write_module() -> tuple[int, int]:
    """Write the generated module with one PNG per size.

    Adjacent string literals concatenate into one, so the comma after every
    block is what keeps the payloads separate: without it the whole thing
    would be a single string and ``for payload in ICON_PNGS`` would iterate
    characters.
    """
    blocks = []
    for size in MODULE_SIZES:
        blocks.append("    # %dx%d" % (size, size))
        blocks.append(_encode(size) + ',')
    source = '\n'.join(blocks)
    ICON_MODULE.write_text(MODULE_HEADER % source, encoding='utf-8')
    return len(source), ICON_MODULE.stat().st_size


def main() -> int:
    ASSETS.mkdir(parents=True, exist_ok=True)
    master = render(SIZE)
    master.save(ASSETS / 'icon.png')
    # Handing each exact size as an appended image stops Pillow from resampling
    # the 256px master for 16..64, which would smear the small marks.
    master.save(ASSETS / 'icon.ico',
                append_images=[render(size) for size in ICO_SIZES if size != SIZE])
    encoded, size = write_module()
    print('icon.png  %d bytes' % (ASSETS / 'icon.png').stat().st_size)
    print('icon.ico  %d bytes' % (ASSETS / 'icon.ico').stat().st_size)
    print('icon.py   %d bytes (embedded %s, %d chars)'
          % (size, ', '.join(str(s) for s in MODULE_SIZES), encoded))
    print('ICON_OK')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
